    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id  bigint NOT NULL REFERENCES app.reviews(id) ON DELETE CASCADE,
    lang       varchar(5) NOT NULL CHECK (lang IN ('ko','en','zh','ja')),
